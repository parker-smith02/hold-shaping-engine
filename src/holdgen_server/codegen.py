"""Generate the client's TypeScript types and the published JSON Schema from the pydantic models.

    python -m holdgen_server.codegen            # write both files
    python -m holdgen_server.codegen --check    # exit 1 if either is stale (CI)

Only the JSON Schema features pydantic emits for our models are handled; anything else
raises, so a model change that needs new mapping fails loudly instead of emitting `any`.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from pydantic.json_schema import models_json_schema

from holdgen import schema as spec_schema

from .models import API_MODELS

ROOT = Path(__file__).resolve().parents[2]
TS_OUT = ROOT / "web" / "src" / "api" / "types.gen.ts"
SCHEMA_OUT = ROOT / "schema" / "hold-spec.schema.json"
HEADER = "// Generated by `python -m holdgen_server.codegen` from the pydantic models. Do not edit.\n"


def _ts(s: dict, defs: dict) -> str:
    if "tsType" in s:
        return s["tsType"]
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            return " | ".join(_wrap(_ts(x, defs)) for x in s[key])
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(_ts(x, defs) for x in s["prefixItems"]) + "]"
        return _wrap(_ts(s.get("items", {}), defs)) + "[]" if s.get("items") else "unknown[]"
    if t == "object":
        if "properties" in s:
            return _object_body(s, defs, indent="  ")
        ap = s.get("additionalProperties", True)
        return f"Record<string, {_ts(ap, defs) if isinstance(ap, dict) else 'unknown'}>"
    if s == {}:
        return "unknown"
    raise ValueError(f"codegen: unsupported schema fragment {s}")


def _wrap(t: str) -> str:
    return f"({t})" if (" | " in t and not t.startswith("(")) else t


def _object_body(s: dict, defs: dict, indent: str = "  ") -> str:
    req = set(s.get("required", []))
    lines = ["{"]
    for name, p in s["properties"].items():
        if "description" in p:
            lines.append(f"{indent}/** {p['description']} */")
        opt = "" if name in req else "?"
        key = name if name.isidentifier() else json.dumps(name)
        lines.append(f"{indent}{key}{opt}: {_ts(p, defs)};")
    lines.append(indent[:-2] + "}")
    return "\n".join(lines)


def generate_ts() -> str:
    models = [spec_schema.HoldSpec, spec_schema.Issue, *API_MODELS]
    _, top = models_json_schema([(m, "validation") for m in models], by_alias=True,
                                ref_template="#/$defs/{model}")
    defs = top["$defs"]
    out = [HEADER]
    for name in sorted(defs):
        d = defs[name]
        if "description" in d:
            out.append("/** " + " ".join(d["description"].split()) + " */")
        if d.get("type") == "object" and "properties" in d:
            out.append(f"export interface {name} {_object_body(d, defs)}\n")
        else:
            out.append(f"export type {name} = {_ts(d, defs)};\n")
    out.append("export type Feature = Dent | Groove;\n")
    return "\n".join(out)


def generate_schema() -> str:
    return json.dumps(spec_schema.json_schema(), indent=2) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    stale = []
    for path, text in ((TS_OUT, generate_ts()), (SCHEMA_OUT, generate_schema())):
        if a.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale generated files (run `python -m holdgen_server.codegen`): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
